/**
 * @file update-user.dto.ts
 * @description DTO для обновления учётной записи пользователя администратором.
 *
 * Используется в маршруте `PATCH /admin/users/:id`.
 * Позволяет администратору изменить тип подписки пользователя и/или его роль.
 * Оба поля опциональны — можно передать одно или оба значения одновременно.
 *
 * Допустимые значения строго ограничены с помощью декоратора `@IsIn`,
 * что предотвращает присвоение недопустимых ролей или несуществующих типов подписок.
 */

import { IsIn, IsOptional, IsString } from "class-validator";

/**
 * DTO обновления пользователя.
 *
 * Описывает поля учётной записи пользователя, доступные для изменения
 * через административный API. Используется для управления доступом:
 * перевода пользователя на платную подписку или назначения роли администратора.
 *
 * @example
 * ```json
 * { "subscription": "paid" }
 * ```
 *
 * @example
 * ```json
 * { "role": "admin", "subscription": "paid" }
 * ```
 */
export class UpdateUserDto {
  /**
   * Новый тип подписки пользователя.
   *
   * Допустимые значения:
   * - `"free"` — бесплатная подписка с ограниченным функционалом и демо-лимитами.
   * - `"paid"` — платная подписка с полным доступом ко всем функциям приложения.
   *
   * @example "paid"
   */
  @IsOptional()
  @IsString()
  @IsIn(["free", "paid"])
  subscription?: string;

  /**
   * Новая роль пользователя в системе.
   *
   * Допустимые значения:
   * - `"user"` — обычный пользователь с доступом только к клиентским маршрутам.
   * - `"admin"` — администратор с полным доступом к административному API (`/admin/*`).
   *
   * Внимание: назначение роли `"admin"` предоставляет полный доступ
   * к управлению персонажами, настройками и другими учётными записями.
   *
   * @example "admin"
   */
  @IsOptional()
  @IsString()
  @IsIn(["user", "admin"])
  role?: string;
}
