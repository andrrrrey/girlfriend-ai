/**
 * @file create-character.dto.ts
 * @description DTO для создания нового AI-персонажа через административный API.
 *
 * Используется в маршруте `POST /admin/characters`.
 * Валидация выполняется с помощью декораторов библиотеки `class-validator`:
 * все поля проходят проверку типа и ограничений перед передачей в сервис.
 *
 * Обязательные поля: `name`, `systemPrompt`.
 * Остальные поля опциональны и при отсутствии получают значения по умолчанию
 * в {@link AdminService.createCharacter}.
 */

import {
  IsArray,
  IsBoolean,
  IsObject,
  IsOptional,
  IsString,
  MinLength,
} from "class-validator";

/**
 * DTO создания AI-персонажа.
 *
 * Описывает структуру тела HTTP-запроса при создании нового персонажа.
 * Персонаж определяет поведение AI-собеседника: его имя, личность,
 * системный промпт (инструкции для языковой модели), голос и визуальное
 * представление.
 *
 * @example
 * ```json
 * {
 *   "name": "Аня",
 *   "systemPrompt": "Ты — дружелюбная и заботливая девушка по имени Аня...",
 *   "personality": { "tone": "warm", "style": "casual" },
 *   "avatarUrl": "https://cdn.example.com/avatars/anya.jpg",
 *   "voiceId": "EXAVITQu4vr4xnSDxMaL",
 *   "tags": ["friendly", "casual"],
 *   "isPublic": true
 * }
 * ```
 */
export class CreateCharacterDto {
  /**
   * Отображаемое имя персонажа.
   *
   * Используется в интерфейсе приложения и в обращениях пользователя.
   * Должно содержать хотя бы один символ.
   *
   * @example "Аня"
   */
  @IsString()
  @MinLength(1)
  name!: string;

  /**
   * Системный промпт — основные инструкции для языковой модели (LLM).
   *
   * Определяет личность, манеру речи, границы поведения и контекст персонажа.
   * Передаётся в параметре `system` при каждом запросе к OpenAI API.
   * Должен содержать хотя бы один символ.
   *
   * @example "Ты — заботливая девушка по имени Аня. Отвечай тепло и с юмором."
   */
  @IsString()
  @MinLength(1)
  systemPrompt!: string;

  /**
   * Дополнительные черты личности персонажа в виде произвольного JSON-объекта.
   *
   * Может содержать любые структурированные данные, описывающие характер,
   * интересы, стиль общения и другие атрибуты персонажа. Используется
   * приложением для расширенной настройки поведения.
   *
   * @example { "tone": "warm", "hobbies": ["music", "cooking"], "age": 23 }
   */
  @IsOptional()
  @IsObject()
  personality?: Record<string, unknown>;

  /**
   * URL изображения аватара персонажа.
   *
   * Ссылка на фото или иллюстрацию, отображаемую в интерфейсе чата
   * рядом с именем персонажа.
   *
   * @example "https://cdn.example.com/avatars/anya.jpg"
   */
  @IsOptional()
  @IsString()
  avatarUrl?: string;

  /**
   * Идентификатор голоса в сервисе ElevenLabs.
   *
   * Используется для синтеза речи: при генерации голосовых ответов
   * персонажа API ElevenLabs получает этот идентификатор для выбора
   * подходящего голосового профиля.
   *
   * @example "EXAVITQu4vr4xnSDxMaL"
   */
  @IsOptional()
  @IsString()
  voiceId?: string;

  /**
   * Массив строковых тегов для категоризации и поиска персонажей.
   *
   * Каждый элемент массива должен быть строкой. Теги могут использоваться
   * для фильтрации персонажей в административном интерфейсе или на
   * клиентской стороне.
   *
   * @example ["friendly", "anime", "casual"]
   */
  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  tags?: string[];

  /**
   * Флаг публичной доступности персонажа.
   *
   * Если `true` — персонаж виден и доступен всем пользователям приложения.
   * Если `false` — персонаж скрыт и доступен только администраторам.
   * По умолчанию в сервисе устанавливается значение `true`.
   *
   * @example true
   */
  @IsOptional()
  @IsBoolean()
  isPublic?: boolean;
}
